static int cursor_x = 0;
static int cursor_y = 0;
static uint32 current_color = COLOR_WHITE;

void fb_init(void)
{
    printk_color(TERM_YELLOW, "[BOOT] Initializing framebuffer...\n");
    
    fb_base = (uint32 *)kmalloc(FB_SIZE);
    if (!fb_base) {
        printk_color(TERM_RED, "[FB] Failed to allocate framebuffer\n");
        return;
    }
    
    fb_clear(COLOR_BLACK);
    fb_initialized = 1;
    
    printk_color(TERM_GREEN, "[BOOT] Framebuffer: %dx%d @ %p\n", 
                 FB_WIDTH, FB_HEIGHT, fb_base);
    
    fb_set_color(COLOR_CYAN);
    fb_draw_string(16, 16, "TorOS v0.4.0 - ARM64 Bare-Metal OS");
    fb_set_color(COLOR_GREEN);
    fb_draw_string(16, 32, "Full Desktop Operating System");
    fb_set_color(COLOR_GRAY);
    fb_draw_string(16, 56, "MMU GICv3 SMP VirtIO TCP/IP GUI Audio Security");
}

void fb_clear(uint32 color)
{
    if (!fb_base) return;
    for (int y = 0; y < FB_HEIGHT; y++)
        for (int x = 0; x < FB_WIDTH; x++)
            fb_base[y * FB_WIDTH + x] = color;
    cursor_x = 0;
    cursor_y = 80;
}

void fb_putpixel(int x, int y, uint32 color)
{
    if (!fb_base || x < 0 || x >= FB_WIDTH || y < 0 || y >= FB_HEIGHT)
        return;
    fb_base[y * FB_WIDTH + x] = color;
}

void fb_draw_char(int x, int y, char c, uint32 color)
{
    if (!fb_base || (uint8)c > 127) return;
    
    const uint8 *bitmap = font8x8[(uint8)c];
    for (int row = 0; row < 8; row++) {
        uint8 row_bits = bitmap[row];
        for (int col = 0; col < 8; col++) {
            if (row_bits & (1 << (7 - col)))
                fb_putpixel(x + col, y + row, color);
        }
    }
}

void fb_set_color(uint32 color)
{
    current_color = color;
}

void fb_draw_string(int x, int y, const char *s)
{
    int orig_x = x;
    while (*s) {
        if (*s == '\n') {
            x = orig_x;
            y += 10;
        } else {
            fb_draw_char(x, y, *s, current_color);
            x += 8;
        }
        s++;
    }
}

void fb_draw_line(int x0, int y0, int x1, int y1, uint32 color)
{
    int dx = (x1 > x0) ? (x1 - x0) : (x0 - x1);
    int dy = (y1 > y0) ? (y1 - y0) : (y0 - y1);
    int sx = (x0 < x1) ? 1 : -1;
    int sy = (y0 < y1) ? 1 : -1;
    int err = dx - dy;
    
    while (1) {
        fb_putpixel(x0, y0, color);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 > -dy) { err -= dy; x0 += sx; }
        if (e2 < dx)  { err += dx; y0 += sy; }
    }
}

void fb_draw_rect(int x, int y, int w, int h, uint32 color)
{
    for (int i = 0; i < w; i++)
        for (int j = 0; j < h; j++)
            fb_putpixel(x + i, y + j, color);
}

void fb_draw_border(int x, int y, int w, int h, uint32 color)
{
    fb_draw_line(x, y, x + w - 1, y, color);
    fb_draw_line(x, y + h - 1, x + w - 1, y + h - 1, color);
    fb_draw_line(x, y, x, y + h - 1, color);
    fb_draw_line(x + w - 1, y, x + w - 1, y + h - 1, color);
}

int fb_is_initialized(void)
{
    return fb_initialized;
}
